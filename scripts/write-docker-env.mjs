/**
 * Writes `.env.docker` from `.env.local`, with the quotes stripped.
 *
 * Docker's `--env-file` (and Compose's `env_file`) is a naive KEY=VALUE
 * parser: it does not strip surrounding quotes, does not expand `${VAR}`, and
 * does not honour `export`. dotenv — which the application itself uses — does
 * all three. Feeding `.env.local` straight to Docker therefore hands the
 * container a DATABASE_URL that literally begins with `"`, and Prisma reports
 * the memorable but useless `Can't reach database server at base`.
 *
 * Run it with `npm run env:docker`, or directly:
 *   node scripts/write-docker-env.mjs [--source .env.local] [--out .env.docker]
 *
 * The output is gitignored by the existing `.env.*` rule. It still contains
 * real credentials — treat it exactly like `.env.local`.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const source = flag('--source', '.env.local');
const out = flag('--out', '.env.docker');

if (!existsSync(source)) {
  console.error(`No ${source} to read. Copy .env.example and fill it in first.`);
  process.exit(1);
}

/** Values Docker needs that differ from the host's. */
const CONTAINER_OVERRIDES = {
  // `localhost` inside a container is the container. Compose overrides this
  // again to `redis`; this value is the one that works for a bare
  // `docker run --env-file .env.docker`.
  REDIS_HOST: 'host.docker.internal',
  // The image bakes NODE_ENV=production, under which slide.config refuses
  // OTP_PROVIDER=mock. Name the environment honestly instead.
  NODE_ENV: 'local',
  HOST: '0.0.0.0',
  PORT: '3000',
};

const values = new Map();
let stripped = 0;

for (const raw of readFileSync(source, 'utf8').split(/\r?\n/)) {
  const line = raw.trim();
  if (!line || line.startsWith('#')) continue;

  const eq = line.indexOf('=');
  if (eq < 0) continue;

  const key = line.slice(0, eq).trim().replace(/^export\s+/, '');
  let value = line.slice(eq + 1).trim();

  const quoted =
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"));
  if (quoted && value.length >= 2) {
    value = value.slice(1, -1);
    stripped += 1;
  }

  values.set(key, value);
}

const overridden = [];
for (const [key, value] of Object.entries(CONTAINER_OVERRIDES)) {
  if (values.get(key) !== value) overridden.push(key);
  values.set(key, value);
}

const header = [
  '# GENERATED by scripts/write-docker-env.mjs — do not edit by hand.',
  `# Source: ${source}. Re-run \`npm run env:docker\` after changing it.`,
  '#',
  '# Quotes are stripped because Docker does not strip them; container-specific',
  '# values are overridden. Contains real credentials — gitignored, keep it so.',
  '',
].join('\n');

writeFileSync(out, `${header}${[...values].map(([k, v]) => `${k}=${v}`).join('\n')}\n`);

console.log(`Wrote ${out}: ${values.size} keys.`);
console.log(`  quotes stripped from ${stripped} value(s)`);
console.log(`  container overrides applied: ${overridden.join(', ') || 'none'}`);

const url = values.get('DATABASE_URL') ?? '';
if (!url) {
  console.warn('  WARNING: DATABASE_URL is empty — the API will not start.');
} else if (!/^postgres(ql)?:\/\//.test(url)) {
  console.warn(`  WARNING: DATABASE_URL does not look like a URL (starts "${url.slice(0, 12)}").`);
}
